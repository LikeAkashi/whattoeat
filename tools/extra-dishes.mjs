function md(r) {
  const stars = '★'.repeat(r.diff);
  return `# ${r.name}的做法

${r.desc}

预估烹饪难度：${stars}

预估卡路里：${r.kcal} 大卡

## 必备原料和工具

${r.ing.map(x => `- ${x}`).join('\n')}

## 计算

每次制作前需要确定计划做几份。一份正好够 2 个人吃。

每份：

${r.calc.map(x => `- ${x}`).join('\n')}

## 操作

${r.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}

## 附加内容

${r.extra.map(x => `- ${x}`).join('\n')}

如果您遵循本指南的制作流程而发现有问题或可以改进的流程，请提出 Issue 或 Pull request 。
`;
}

let n = 0;
